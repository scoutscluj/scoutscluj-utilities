<details class="guidance">
	<summary>Cum obțin certificatul (CIC)?</summary>
	<div>
		<h3>Online, gratuit · aproximativ 10 minute</h3>
		<p>
			Cea mai simplă variantă este HUB MAI. Creează un cont și validează-l prin contul tău de pe
			<a href="https://www.ghiseul.ro/ghiseul/public/" target="_blank" rel="noopener noreferrer"
				>Ghișeul.ro</a
			>. Deschide serviciul pentru certificatul de integritate comportamentală, urmează pașii
			cererii și descarcă certificatul PDF emis.
		</p>
		<a href="https://hub.mai.gov.ro/serviciu/view?id=90" target="_blank" rel="noopener noreferrer"
			>Obține certificatul de integritate · HUB MAI ↗</a
		>
		<p>Serviciul oficial este gratuit pentru cetățenii români eligibili, cu un cont validat.</p>
		<a
			href="https://hub.mai.gov.ro/site/despre-validare-cont"
			target="_blank"
			rel="noopener noreferrer">Cum îmi validez contul HUB MAI? ↗</a
		>
		<h3>Alternative cu plată</h3>
		<p>
			Poți apela și la servicii cu plată:
			<a href="https://roghiseul.ro" target="_blank" rel="noopener noreferrer">roghiseul.ro ↗</a>
			sau <a href="https://caziere.ro" target="_blank" rel="noopener noreferrer">caziere.ro ↗</a>.
		</p>
		<h3>Fizic, în Cluj-Napoca</h3>
		<p>
			Mergi cu un act de identitate valabil la Secția de Poliție nr. 1, Str. Decebal nr. 26, și
			solicită certificatul de integritate comportamentală, indiferent de județul de reședință.
		</p>
		<p>
			Încarcă PDF-ul original sau o scanare/fotografie lizibilă a documentului pe hârtie. Dosarul
			din aplicație este anual; valabilitatea înscrisă de emitent pe fiecare certificat rămâne cea
			oficială.
		</p>
	</div>
</details>

